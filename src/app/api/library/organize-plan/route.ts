import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { withAdmin } from "@/lib/route-helpers";
import { buildOrganizePlan } from "@/lib/library/organize-plan";

// GET /api/library/organize-plan — project the bookstore shelves onto
// the disk, as a REVIEWABLE shell script rather than an action.
//
// The library mount is read-only by design and this server never moves
// files. Instead, this endpoint emits the move plan the metadata
// implies (lib/library/organize-plan): every shelved book whose current
// top-level folder differs from its genre gets a `mv -n` into
// `<its scan root>/<genre>/`, keeping its filename. The admin downloads
// the script, reads it, runs it on the host, and rescans — the
// content-hash re-link keeps all progress, highlights, notes, and ink
// attached across the moves.
//
// `mv -n` (no-clobber) means a name collision in the target folder is
// skipped rather than overwritten; the rescan surfaces what remains.
// Unshelved (Unsorted) books and books outside every enabled root are
// never planned.
export const GET = withAdmin(async () => {
  const [books, locations] = await Promise.all([
    prisma.book.findMany({
      where: { genre: { not: null } },
      select: { filePath: true, genre: true },
      orderBy: { filePath: "asc" },
    }),
    prisma.scanLocation.findMany({
      where: { enabled: true },
      select: { path: true },
    }),
  ]);

  const plan = buildOrganizePlan(
    books.map((b) => ({ filePath: b.filePath, genre: b.genre! })),
    locations.map((l) => l.path),
  );

  const quote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;
  const script = [
    "#!/usr/bin/env bash",
    "# organize-plan — generated by homelab-reader from the assigned shelves.",
    "# REVIEW BEFORE RUNNING. Moves use mv -n (no overwrite); a skipped line",
    "# means the target name already exists. After running, trigger a rescan:",
    "# the content-hash re-link keeps progress and annotations across moves.",
    `# Plan: ${plan.moves.length} move(s), ${plan.alreadyPlaced} already in place, ${plan.outsideRoots} outside the library roots (skipped).`,
    "set -euo pipefail",
    "",
    ...plan.dirs.map((d) => `mkdir -p ${quote(d)}`),
    "",
    ...plan.moves.map(([from, to]) => `mv -n ${quote(from)} ${quote(to)}`),
    "",
    `echo "Done — ${plan.moves.length} file(s) moved. Rescan the library to re-link."`,
    "",
  ].join("\n");

  return new NextResponse(script, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": 'attachment; filename="organize-library.sh"',
    },
  });
});
